#!/usr/bin/env python3
"""
Generates the iOS string catalogs from the Android string files, so copy has one source.

Each module's `values*/strings.xml` (`src/commonMain/composeResources`, or `:shared`'s Android
`src/androidMain/res`) becomes one `.xcstrings` table in the output directory: `:shared` → `Localizable.xcstrings` (the default table), `:features:<x>` →
`<X>.xcstrings`, plus `StringTable.swift` naming them. That's one table per module, mirroring Compose's one `Res` per module, so the same key
in two modules can't collide. Swift reads them with `tr(_:_:table:)` (iosApp/iosApp/DesignSystem/Strings.swift).

Converted on the way: Android escapes (\\' \\" \\n \\t \\\\), and format args `%1$s` → `%1$@`,
`%1$d` → `%1$lld`, so `String(format:)` takes Swift `String` and `Int`. Plurals become plural variations.

Fails, naming the keys, if a language lacks a key the source language has: CLAUDE.md says no string
ships in one language only. Writes a catalog only when its content changed, so Xcode doesn't rebuild
for nothing.

Usage: generate-ios-strings.py <repo root> <output dir>
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SOURCE_LANGUAGE = "en"


def language(values_dir: str) -> str:
    """`values` → en, `values-pt-rBR` → pt-BR, `values-es` → es."""
    if values_dir == "values":
        return SOURCE_LANGUAGE
    parts = values_dir.split("-")[1:]
    return "-".join(p[1:] if p.startswith("r") and len(p) == 3 else p for p in parts)


def convert(text: str) -> str:
    text = re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), text)
    text = re.sub(r"%(\d+\$)?s", r"%\1@", text)
    return re.sub(r"%(\d+\$)?d", r"%\1lld", text)


def unit(text: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": convert(text)}}


def parse(path: Path) -> dict:
    entries = {}
    for node in ET.parse(path).getroot():
        name = node.get("name")
        if node.tag == "string":
            entries[name] = unit("".join(node.itertext()))
        elif node.tag == "plurals":
            entries[name] = {"variations": {"plural": {
                item.get("quantity"): unit("".join(item.itertext())) for item in node.findall("item")
            }}}
    return entries


def table_name(module_dir: Path, root: Path) -> str:
    if module_dir == root / "shared":
        return "Localizable"
    return module_dir.name[0].upper() + module_dir.name[1:]


def catalog(resources: Path) -> tuple[dict, list[str]]:
    by_language = {
        language(d.name): parse(d / "strings.xml")
        for d in sorted(resources.glob("values*")) if (d / "strings.xml").exists()
    }
    source = by_language[SOURCE_LANGUAGE]
    missing = [
        f"{lang}: {key}"
        for lang, entries in by_language.items() for key in source if key not in entries
    ]
    strings = {
        key: {
            "extractionState": "manual",
            "localizations": {lang: entries[key] for lang, entries in by_language.items() if key in entries},
        }
        for key in sorted(source)
    }
    return {"sourceLanguage": SOURCE_LANGUAGE, "strings": strings, "version": "1.0"}, missing


def resources_of(module: Path) -> Path:
    """Where a module's `values*/strings.xml` live: the feature modules' Compose Resources, or `:shared`'s
    Android `res` (its Compose shell is Android-only, and Compose Resources would put Compose in iOS)."""
    for resources in (module / "src/commonMain/composeResources", module / "src/androidMain/res"):
        if (resources / "values/strings.xml").exists():
            return resources
    return module / "src/commonMain/composeResources"


def main(root: Path, out: Path) -> int:
    out.mkdir(parents=True, exist_ok=True)
    modules = [root / "shared", *sorted((root / "features").iterdir())]
    problems = []
    for module in modules:
        resources = resources_of(module)
        if not (resources / "values/strings.xml").exists():
            continue
        content, missing = catalog(resources)
        problems += [f"{module.relative_to(root)} → {m}" for m in missing]
        target = out / f"{table_name(module, root)}.xcstrings"
        text = json.dumps(content, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        if not target.exists() or target.read_text() != text:
            target.write_text(text)
            print(f"generated {target.name}")
    # The table names as a Swift enum, so a Swift caller can't name a table that doesn't exist.
    tables = [table_name(m, root) for m in modules if (resources_of(m) / "values/strings.xml").exists()]
    cases = "\n".join(f'    case {t[0].lower() + t[1:]} = "{t}"' for t in tables)
    swift = (
        "// Generated by scripts/generate-ios-strings.py from the modules' strings.xml. Do not edit.\n\n"
        "/// The string tables, one per module. See `tr(_:_:table:)`.\n"
        f"enum StringTable: String {{\n{cases}\n}}\n"
    )
    enum_file = out / "StringTable.swift"
    if not enum_file.exists() or enum_file.read_text() != swift:
        enum_file.write_text(swift)
        print(f"generated {enum_file.name}")
    if problems:
        print("Strings missing a translation:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()))
