#!/usr/bin/env python3
"""Generates `TanukiSymbols.kt`: the Material Symbols Rounded glyphs the Android app uses, as ImageVectors.

Usage: python3 -I scripts/generate-material-symbols.py \
           assets/designSystem/src/commonMain/kotlin/app/tanuki/assets/designSystem/component/TanukiSymbols.kt

The design system asks for Material Symbols Rounded at wght 400, GRAD 0, opsz 24, with FILL 0 at rest and
FILL 1 when selected. Rather than bundle the variable font, each glyph is fetched from google/material-design-icons
(`symbols/web/<name>/materialsymbolsrounded/<name>[_fill1]_24px.svg`, which are exactly those axes) and its path
written out. To add an icon, add a row to SYMBOLS and re-run. Never edit the output by hand.
"""

from __future__ import annotations

import re
import sys
import subprocess
from pathlib import Path

# (Kotlin name, Material Symbols name, also emit the FILL 1 variant as `<Name>Filled`)
SYMBOLS = [
    ("ArrowBack", "arrow_back", False),
    ("ArrowDownward", "arrow_downward", False),
    ("ArrowUpward", "arrow_upward", False),
    ("Bookmark", "bookmark", True),
    ("Check", "check", False),
    ("Close", "close", False),
    ("CollectionsBookmark", "collections_bookmark", True),
    ("Contrast", "contrast", False),
    ("Delete", "delete", False),
    ("Download", "download", False),
    ("DownloadDone", "download_done", False),
    ("Error", "error", False),
    ("ExpandMore", "expand_more", False),
    ("Extension", "extension", False),
    ("FilterList", "filter_list", False),
    ("FormatListBulleted", "format_list_bulleted", False),
    ("Home", "home", True),
    ("Insights", "insights", True),
    ("KeyboardDoubleArrowDown", "keyboard_double_arrow_down", False),
    ("KeyboardDoubleArrowUp", "keyboard_double_arrow_up", False),
    ("Label", "label", False),
    ("Lock", "lock", False),
    ("MoreVert", "more_vert", False),
    ("Pause", "pause", False),
    ("PlayArrow", "play_arrow", False),
    ("RemoveDone", "remove_done", False),
    ("Search", "search", False),
    ("SelectAll", "select_all", False),
    ("Settings", "settings", True),
    ("SkipNext", "skip_next", False),
    ("SkipPrevious", "skip_previous", False),
    ("Tune", "tune", False),
    ("VerifiedUser", "verified_user", False),
    ("Wifi", "wifi", False),
]

URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{0}/materialsymbolsrounded/{0}{1}_24px.svg"
HEADER = "// Generated by scripts/generate-material-symbols.py from Material Symbols Rounded. Do not edit.\n"


def path_of(name: str, fill: bool) -> tuple[str, int, int]:
    """The glyph's path plus its box: (path, size, top). Most glyphs are `0 -960 960 960`; a few are 24×24."""
    # curl rather than urllib: a python.org Python has no CA bundle until its certificate script is run.
    svg = subprocess.run(["curl", "-fsSL", URL.format(name, "_fill1" if fill else "")],
                         check=True, capture_output=True, text=True).stdout
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        raise ValueError(f"unexpected SVG for {name}: {svg[:200]}")
    if 'viewBox="0 -960 960 960"' in svg:
        return paths[0], 960, -960
    if 'height="24" width="24"' in svg and "viewBox" not in svg:
        return paths[0], 24, 0
    raise ValueError(f"unexpected box for {name}: {svg[:200]}")


def main(out: Path) -> None:
    lines = [HEADER.rstrip("\n"), "package app.tanuki.assets.designSystem.component", "",
             "import androidx.compose.ui.graphics.vector.ImageVector", "",
             "/**",
             " * Material Symbols Rounded (wght 400, GRAD 0, opsz 24), the Android icon set. `<Name>` is FILL 0, for",
             " * icons at rest; `<Name>Filled` is FILL 1, for the selected state (active tab, bookmark set).",
             " */",
             "object TanukiSymbols {"]
    for kotlin, name, filled in SYMBOLS:
        variants = [(kotlin, False)] + ([(kotlin + "Filled", True)] if filled else [])
        for ident, fill in variants:
            path, size, top = path_of(name, fill)
            lines += [f"    /** `{name}`{', FILL 1' if fill else ''}. */",
                      f'    val {ident}: ImageVector by lazy {{ materialSymbol("{ident}", {size}f, {top}f, "{path}") }}']
    lines += ["}", ""]
    out.write_text("\n".join(lines))
    print(f"{len(SYMBOLS)} symbols → {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
