#!/usr/bin/env python3
"""Generates the iOS design tokens from the Tanuki Design System's tokens.json.

Usage: python3 -I scripts/generate-ios-tokens.py iosApp/design/tokens.json iosApp/iosApp \
           assets/designSystem/src/commonMain/kotlin/app/tanuki/assets/designSystem/ReaderColors.kt

`tokens.json` is a checked-in copy of the design-system artifact's `project/tokens.json`. Refresh it
when the design changes, then re-run this. The script writes:

- `Assets.xcassets/Tanuki/<name>.colorset`, one per color token (Any + Dark appearance), replacing every
  colorset there, and `Assets.xcassets/AccentColor.colorset` from `accent`.
- `DesignSystem/TanukiColors.swift` (`Color.tk.*`) and `DesignSystem/TanukiTokens.swift` (`TK.Space`,
  `TK.Radius`, `TK.Size`).

- With the optional third argument, the Android reader grounds (`reader-*`) as `ReaderColors.kt`. Android's
  full palette is still hand-kept in `TanukiColors.kt` (it predates these tokens); the reader colours are
  the first generated slice of it.

Never edit the outputs by hand. `glass-*` and `scrim` are skipped: they exist for the web previews
(Liquid Glass and the system scrim are drawn by iOS itself), and Swift never paints them.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

SKIPPED = re.compile(r"^(glass-.*|scrim)$")
HEADER = "// Generated by scripts/generate-ios-tokens.py from iosApp/design/tokens.json. Do not edit.\n"


def camel(name: str) -> str:
    head, *rest = name.replace(".", "_").split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def rgba(value: str) -> tuple[int, int, int, float]:
    """`#rrggbb` or `rgba(r,g,b,a)` → (r, g, b, alpha)."""
    if value.startswith("#"):
        return int(value[1:3], 16), int(value[3:5], 16), int(value[5:7], 16), 1.0
    match = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", value)
    if not match:
        raise ValueError(f"unsupported color value: {value}")
    r, g, b, a = match.groups()
    return int(r), int(g), int(b), float(a)


def colorset(light: str, dark: str) -> dict:
    def entry(value: str, appearance: str | None) -> dict:
        r, g, b, a = rgba(value)
        color = {
            "color": {
                "color-space": "srgb",
                "components": {"red": f"0x{r:02X}", "green": f"0x{g:02X}", "blue": f"0x{b:02X}", "alpha": f"{a:.3f}"},
            },
            "idiom": "universal",
        }
        if appearance:
            color = {"appearances": [{"appearance": "luminosity", "value": appearance}], **color}
        return color

    return {"colors": [entry(light, None), entry(dark, "dark")], "info": {"author": "xcode", "version": 1}}


def write_json(path: Path, data: dict) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / "Contents.json").write_text(json.dumps(data, indent=2) + "\n")


def main(tokens_path: Path, app: Path) -> None:
    tokens = json.loads(tokens_path.read_text())
    colors = tokens["color"]["tokens"]
    by_name = {t["name"]: t["value"] for t in colors}

    def resolve(value: str) -> str:
        ref = re.fullmatch(r"\{(.+)\}", value)
        return resolve(by_name[ref.group(1)]) if ref else value

    def themed(value) -> tuple[str, str]:
        if isinstance(value, str):
            return resolve(value), resolve(value)
        return resolve(value["light"]), resolve(value["dark"])

    # Colorsets: replace the whole folder so a token removed from the design disappears here too.
    folder = app / "Assets.xcassets/Tanuki"
    shutil.rmtree(folder, ignore_errors=True)
    write_json(folder, {"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}})
    emitted = [t for t in colors if not SKIPPED.match(t["name"])]
    for token in emitted:
        write_json(folder / f"{camel(token['name'])}.colorset", colorset(*themed(token["value"])))
    write_json(app / "Assets.xcassets/AccentColor.colorset", colorset(*themed(by_name["accent"])))

    lines = [HEADER, "import SwiftUI", "", "/// The Tanuki palette, iOS dialect: `Color.tk.canvas`, `Color.tk.ink`, …",
             "///", "/// Each token is a colorset in `Assets.xcassets/Tanuki/` with a Day (Any) and a Night (Dark)",
             "/// appearance, so it follows the theme by itself. Usage notes come from the design system.",
             "extension Color {", "    enum tk {"]
    for token in emitted:
        lines.append(f"        /// {token['usage']}")
        lines.append(f'        static let {camel(token["name"])} = Color("Tanuki/{camel(token["name"])}")')
    covers = [camel(t["name"]) for t in emitted if t["name"].startswith("cover-") and t["name"] != "cover-scrim"]
    lines += ["", "        /// The fallback cover grounds, in design order. Pick one by hashing the manga id.",
              f"        static let coverFallbacks: [Color] = [{', '.join(covers)}]", "    }", "}", ""]
    (app / "DesignSystem/TanukiColors.swift").write_text("\n".join(lines))

    def group(title: str, doc: str, items: list[dict], strip: str) -> list[str]:
        out = [f"    /// {doc}", f"    enum {title} {{"]
        for token in items:
            suffix = token["name"].removeprefix(strip)
            # `space-0-5` → `s0_5`: a Swift name can't start with a digit, and `05` would read as five.
            name = "s" + suffix.replace("-", "_") if suffix[0].isdigit() else camel(suffix)
            value = token["value"].removesuffix("px")
            out += [f"        /// {token['usage']}", f"        static let {name}: CGFloat = {value}"]
        return out + ["    }"]

    lines = [HEADER, "import CoreGraphics", "", "/// Spacing, radii and sizes from the design system, in points.",
             "/// Motion has no token family; it lives in `TanukiMotion.swift`.", "enum TK {"]
    lines += group("Space", "4pt grid.", tokens["spacing"]["tokens"], "space-")
    lines += [""] + group("Radius", "Use continuous corners (`.rect(cornerRadius:style: .continuous)`).",
                          tokens["radius"]["tokens"], "radius-")
    lines += [""] + group("Size", "Touch targets, bars, the cover ratio and icon sizes.", tokens["size"]["tokens"], "")
    lines += ["}", ""]
    (app / "DesignSystem/TanukiTokens.swift").write_text("\n".join(lines))
    print(f"{len(emitted)} colors, {len(covers)} cover fallbacks → {app}")


def android_reader_colors(tokens_path: Path, out: Path) -> None:
    """The `reader-*` tokens (theme-invariant) as a Compose `ReaderColors` object."""
    reader = [t for t in json.loads(tokens_path.read_text())["color"]["tokens"] if t["name"].startswith("reader-")]
    lines = [HEADER.rstrip("\n"), "package app.tanuki.assets.designSystem", "",
             "import androidx.compose.ui.graphics.Color", "",
             "/** The reader's page grounds and the ink on sepia. Theme-invariant: the reader picks its own ground. */",
             "object ReaderColors {"]
    for token in reader:
        r, g, b, a = rgba(token["value"])
        name = camel(token["name"].removeprefix("reader-"))
        lines += [f"    /** {token['usage']} */",
                  f"    val {name[:1].upper() + name[1:]} = Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})"]
    out.write_text("\n".join(lines + ["}", ""]))
    print(f"{len(reader)} reader colors → {out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
    if len(sys.argv) > 3:
        android_reader_colors(Path(sys.argv[1]), Path(sys.argv[3]))
